import assert from 'node:assert/strict';
import { selectJobQueue } from '../dist/job-queue.js';
const job = (pageId, suffix) => ({ url: `https://example.com/${suffix}`, notion: { pageId } });
const a=job('a','old-a'), b=job('b','old-b'), c=job('c','older'), added=job('new','newest');
let snapshots=[[a,b,c],[added,a,c],[added,a,c]];
let calls=0;
const queue=selectJobQueue([a,b,c], { live:true, limit:3, reload:async()=>{ calls++; return snapshots.shift(); }, shouldSkip:()=>false });
assert.equal((await queue.next()).value.url,a.url);
assert.equal((await queue.next()).value.url,added.url, 'Newly added top record must replace the stale second choice');
assert.equal((await queue.next()).value.url,c.url);
assert.equal((await queue.next()).done,true);
assert.equal(calls,3);
let staticCalls=0;
const finite=selectJobQueue([a,b,c],{live:true,limit:2,reload:async()=>{staticCalls++;return[a,b,c];},shouldSkip:url=>url===a.url});
assert.equal((await finite.next()).value.url,b.url);
assert.equal((await finite.next()).done,true,'Do not backfill older links outside current top N');
const changed=selectJobQueue([a,b],{live:true,limit:2,reload:async()=>[job('a',Math.random().toString()),b],shouldSkip:()=>false});
assert.equal((await changed.next()).value.notion.pageId,'a');
assert.equal((await changed.next()).value.notion.pageId,'b','Do not reprocess same Notion page after URL edits');
let step=0;
const failure=selectJobQueue([a,b],{live:true,limit:2,reload:async()=>{if(step++)throw Error('API offline');return[a,b];},shouldSkip:()=>false});
await failure.next();
await assert.rejects(failure.next(),/API offline/);
const file=[];
for await(const candidate of selectJobQueue([a,b,c],{live:false,limit:2,reload:async()=>{throw Error('must not refresh file source');},shouldSkip:url=>url===a.url}))file.push(candidate);
assert.deepEqual(file,[b,c]);
console.log('PASS: live queue refresh, changed/removed records, top N boundary, duplicate protection, file queues, and fail-closed refresh.');
